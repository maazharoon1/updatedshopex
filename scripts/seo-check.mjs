// Validate actual build output, including every public, indexable route.
import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { projects } from '../src/data/projects.ts';
import { site, canonicalUrl, homeSeo, videoSeo, serializeJsonLd } from '../src/lib/seo.ts';
const preview = process.argv.includes('--preview');
const directory = process.argv.find(arg => arg.startsWith('--dir='))?.slice(6) || 'dist';
const read = path => readFile(`${directory}/${path}`, 'utf8');
const decode = text => text.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const pages = [homeSeo, ...projects.filter(p => p.type === 'video' && p.videoUrl).map(p => videoSeo(p, projects))];
const home = await read('index.html');
const bodies = html => html.match(/<body>[\s\S]*<\/body>/)?.[0];
const titles = new Set(), descriptions = new Set();
for (const page of pages) {
  const html = await read(page.canonicalPath === '/' ? 'index.html' : `${page.canonicalPath.slice(1)}/index.html`);
  const meta = name => {
    const matches = [...html.matchAll(/<meta (?:name|property)="([^"]+)" content="([^"]*)"\s*\/?\s*>/g)].filter(m => m[1] === name);
    assert.equal(matches.length, 1, `${page.canonicalPath}: one ${name}`);
    return decode(matches[0][2]);
  };
  const title = decode(html.match(/<title>([^<]*)<\/title>/)?.[1] || '');
  assert.equal(title, page.title);
  assert(!titles.has(title), `Duplicate title: ${title}`); titles.add(title);
  assert.equal(meta('description'), page.description);
  assert(!descriptions.has(page.description), `Duplicate description: ${page.canonicalPath}`); descriptions.add(page.description);
  assert.equal([...html.matchAll(/rel="canonical"/g)].length, 1);
  assert.equal(decode(html.match(/<link rel="canonical" href="([^"]+)"/)?.[1] || ''), canonicalUrl(page.canonicalPath));
  assert.equal(meta('og:url'), canonicalUrl(page.canonicalPath));
  assert.equal(meta('og:title'), title); assert.equal(meta('twitter:title'), title);
  assert.equal(meta('og:description'), page.description); assert.equal(meta('twitter:description'), page.description);
  assert.equal(meta('og:image'), page.image); assert.equal(meta('twitter:image'), page.image);
  assert.equal(meta('og:image:alt'), page.imageAlt); assert.equal(meta('twitter:image:alt'), page.imageAlt);
  assert.equal(meta('twitter:card'), 'summary_large_image');
  assert.equal(meta('robots'), preview ? 'noindex,follow' : 'index,follow,max-image-preview:large');
  assert(!html.includes('name="keywords"')); assert(!html.includes('shopex-six.vercel.app'));
  const scripts = [...html.matchAll(/<script id="shopex-schema" type="application\/ld\+json">([^<]*)<\/script>/g)];
  assert.equal(scripts.length, 1);
  const data = JSON.parse(scripts[0][1]);
  assert.equal(data['@context'], 'https://schema.org');
  const [organization, website, webpage] = data['@graph'];
  assert.equal(organization['@type'], 'Organization'); assert.equal(organization.name, site.name);
  assert.equal(organization.url, `${site.origin}/`); assert.equal(organization.logo, `${site.origin}${site.logo}`);
  assert(!organization.address && !organization.sameAs && !organization.aggregateRating);
  assert.equal(website['@type'], 'WebSite'); assert.equal(website.alternateName, 'Shopex');
  assert.equal(webpage.url, canonicalUrl(page.canonicalPath)); assert.equal(webpage.name, title);
  assert.equal(bodies(html), bodies(home), 'Generated pages must retain the identical app shell and scripts');
  for (const [, path] of html.matchAll(/(?:src|href)="(\/assets\/[^"?#]+)"/g)) await access(`${directory}${path}`);
}
const sitemap = await read('sitemap.xml');
assert(sitemap.startsWith('<?xml version="1.0" encoding="UTF-8"?>'));
assert(sitemap.includes('xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"'));
const urls = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map(m => decode(m[1]));
assert.deepEqual(urls, preview ? [] : pages.map(p => canonicalUrl(p.canonicalPath)));
assert.equal(new Set(urls).size, urls.length);
assert(urls.every(url => !new URL(url).search && !new URL(url).hash));
const robots = await read('robots.txt');
assert(robots.includes('User-agent: *\nAllow: /'));
assert(!robots.includes('Disallow: /'));
assert.equal(robots.includes(`Sitemap: ${site.origin}/sitemap.xml`), !preview);
assert.equal(canonicalUrl('/video/v01/?ref=test#fragment'), `${site.origin}/video/v01`);
assert(!serializeJsonLd({ value: '</script><script>alert(1)</script>' }).includes('<'));
await access(`public${site.logo}`);
console.log(`PASS: ${pages.length} route heads, unique titles/descriptions, canonicals, OG/Twitter, JSON-LD, unchanged app shells, referenced local bundles, sitemap and robots (${preview ? 'preview' : 'production'}).`);
